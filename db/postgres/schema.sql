-- PostgreSQL 16 — base ecommerce: inventario por sucursal.
-- Fragmentación HORIZONTAL (D8): inventario y movimientos están particionadas
-- por sucursal (PARTITION BY LIST). Cada sucursal lee y escribe solo su fragmento;
-- se demuestra con EXPLAIN (partition pruning).
-- Lo aplica scripts/postgres/esquema.sh en db2; el standby (db3) lo recibe por streaming.

CREATE TABLE IF NOT EXISTS sucursales (
  id      smallint PRIMARY KEY,
  nombre  text NOT NULL,
  ciudad  text NOT NULL,
  region  text NOT NULL
);

-- producto_id es una referencia lógica al catálogo de MongoDB.
CREATE TABLE IF NOT EXISTS productos_sucursal (
  producto_id   integer        NOT NULL,
  sucursal_id   smallint       NOT NULL REFERENCES sucursales (id),
  precio_local  numeric(10,2)  NOT NULL CHECK (precio_local > 0),
  activo        boolean        NOT NULL DEFAULT true,
  PRIMARY KEY (producto_id, sucursal_id)
);

-- La PK de una tabla particionada debe incluir la llave de partición (sucursal_id).
CREATE TABLE IF NOT EXISTS inventario (
  producto_id  integer      NOT NULL,
  sucursal_id  smallint     NOT NULL,
  cantidad     integer      NOT NULL CHECK (cantidad >= 0),
  actualizado  timestamptz  NOT NULL DEFAULT now(),
  PRIMARY KEY (producto_id, sucursal_id),
  FOREIGN KEY (producto_id, sucursal_id) REFERENCES productos_sucursal (producto_id, sucursal_id)
) PARTITION BY LIST (sucursal_id);

CREATE TABLE IF NOT EXISTS inventario_s1 PARTITION OF inventario FOR VALUES IN (1);
CREATE TABLE IF NOT EXISTS inventario_s2 PARTITION OF inventario FOR VALUES IN (2);
CREATE TABLE IF NOT EXISTS inventario_s3 PARTITION OF inventario FOR VALUES IN (3);
CREATE TABLE IF NOT EXISTS inventario_s4 PARTITION OF inventario FOR VALUES IN (4);
CREATE TABLE IF NOT EXISTS inventario_s5 PARTITION OF inventario FOR VALUES IN (5);

-- pedido_id es una referencia lógica a MySQL.
CREATE TABLE IF NOT EXISTS reservas (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id    bigint       NOT NULL,
  producto_id  integer      NOT NULL,
  sucursal_id  smallint     NOT NULL REFERENCES sucursales (id),
  cantidad     integer      NOT NULL CHECK (cantidad > 0),
  estado       text         NOT NULL DEFAULT 'ACTIVA' CHECK (estado IN ('ACTIVA', 'LIBERADA')),
  creado       timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_reservas_pedido ON reservas (pedido_id);

CREATE TABLE IF NOT EXISTS movimientos (
  id           bigint GENERATED BY DEFAULT AS IDENTITY,
  sucursal_id  smallint     NOT NULL REFERENCES sucursales (id),
  producto_id  integer      NOT NULL,
  tipo         text         NOT NULL CHECK (tipo IN ('ENTRADA', 'SALIDA', 'LIBERACION', 'AJUSTE')),
  cantidad     integer      NOT NULL CHECK (cantidad > 0),
  pedido_id    bigint,
  creado       timestamptz  NOT NULL DEFAULT now(),
  PRIMARY KEY (id, sucursal_id)
) PARTITION BY LIST (sucursal_id);

CREATE TABLE IF NOT EXISTS movimientos_s1 PARTITION OF movimientos FOR VALUES IN (1);
CREATE TABLE IF NOT EXISTS movimientos_s2 PARTITION OF movimientos FOR VALUES IN (2);
CREATE TABLE IF NOT EXISTS movimientos_s3 PARTITION OF movimientos FOR VALUES IN (3);
CREATE TABLE IF NOT EXISTS movimientos_s4 PARTITION OF movimientos FOR VALUES IN (4);
CREATE TABLE IF NOT EXISTS movimientos_s5 PARTITION OF movimientos FOR VALUES IN (5);
CREATE INDEX IF NOT EXISTS ix_movimientos_pedido   ON movimientos (pedido_id);
CREATE INDEX IF NOT EXISTS ix_movimientos_producto ON movimientos (sucursal_id, producto_id);

-- Privilegio mínimo para la app: solo datos. No puede crear, borrar ni vaciar tablas.
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO app_ecommerce;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO app_ecommerce;
